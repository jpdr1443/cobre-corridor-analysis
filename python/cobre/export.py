"""Export: one Excel workbook per assessment part + the data model as CSV."""
from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook

from .result import Result
from .xl import font, link, title, widths, write_df

# Data model columns (fact table)
FACT_COLUMNS = [
    "transaction_id", "user_id", "transaction_date", "transaction_time", "hour",
    "weekday_n", "weekday", "month", "quarter", "corridor", "source_country",
    "destination_country", "user_segment", "user_segment_profile", "country",
    "user_status", "amount_usd", "amount_band", "over_threshold", "status",
    "is_success", "is_failed", "success_usd", "failed_usd",
]

# Target workbook by the module that produced each table
WORKBOOKS = {
    "Part1_Data_Analysis.xlsx": ("Part 1 · Data analysis (includes data quality checks)",
                                   ["quality", "p1_corridors", "p1_users", "p1_time"]),
    "Part2_Root_Cause.xlsx": ("Part 2 · Root cause and revenue impact", ["p2_root_cause"]),
    "Part3_Recommendation.xlsx": ("Part 3 · Decision matrix for the corridor to prioritize", ["p3_strategy"]),
}


def _workbook(path: Path, heading: str, tables: dict[str, pd.DataFrame]) -> Path:
    wb = Workbook()
    idx = wb.active
    idx.title = "index"
    idx.sheet_view.showGridLines = False
    widths(idx, {"A": 2, "B": 34, "C": 10})
    title(idx, heading, "Generated by python main.py. Click a table to open its sheet.")
    idx.cell(row=5, column=2, value="Table").font = font(10, True)
    idx.cell(row=5, column=3, value="Rows").font = font(10, True)
    for i, (name, t) in enumerate(tables.items(), start=6):
        sheet = name[:31]
        ws = wb.create_sheet(sheet)
        ws.sheet_view.showGridLines = False
        widths(ws, {"A": 2, **{chr(66 + j): 16 for j in range(24)}})
        link(ws, 1, 2, "← index", "index", size=9)
        ws.cell(row=2, column=2, value=name).font = font(12, True)
        write_df(ws, 4, 2, t if not isinstance(t.columns, pd.MultiIndex) else _flat(t))
        ws.freeze_panes = "C5"
        link(idx, i, 2, name, sheet)
        idx.cell(row=i, column=3, value=len(t)).font = font(10)
    wb.save(path)
    return path


def _flat(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    out.columns = ["_".join(map(str, c)) for c in out.columns]
    return out


def export(results: list[Result], fact: pd.DataFrame, users: pd.DataFrame,
           out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    by_module = {r.name: r for r in results}
    paths = {}
    for filename, (heading, modules) in WORKBOOKS.items():
        tables = {k: v for m in modules for k, v in by_module[m].tables.items()}
        paths[filename] = _workbook(out_dir / filename, heading, tables)

    fact_out = fact[FACT_COLUMNS].copy()
    fact_out["amount_band"] = fact_out["amount_band"].astype(str)
    fact_out.to_csv(out_dir / "fact_transactions.csv", index=False)
    users.to_csv(out_dir / "dim_users.csv", index=False)
    paths["fact"] = out_dir / "fact_transactions.csv"
    return paths
